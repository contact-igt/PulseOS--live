function enquiriesSheet(wb: ExcelJS.Workbook, facts: ReportFacts) {
  const tz = facts.period.timezone;
  addSheet(
    wb,
    "Enquiries",
    [
      { header: "Created", key: "created", width: 20 }, { header: "Patient", key: "patient", width: 24 }, { header: "Phone", key: "phone", width: 16 },
      { header: "Service", key: "service", width: 20 }, { header: "Source", key: "source", width: 22 }, { header: "Branch", key: "branch", width: 18 },
      { header: "Team Member", key: "owner", width: 20 }, { header: "Stage", key: "stage", width: 20 }, { header: "Latest outcome", key: "outcome", width: 22 },
      { header: "Contacted", key: "contacted", width: 11 }, { header: "Appointment booked", key: "booked", width: 19 }, { header: "Attended", key: "attended", width: 10 },
      { header: "Converted", key: "converted", width: 11 },
    ],
    facts.enquiries.map((e) => ({
      created: dateTime(e.createdAt, tz), patient: e.patientName ?? UNKNOWN_PATIENT, phone: e.phone, service: e.service, source: e.sourceLabel ?? e.bucket,
      branch: e.branchName ?? "", owner: e.ownerUserId ? (e.ownerName ?? "Former staff") : "Unassigned", stage: STAGE_LABEL[e.stage] ?? e.stage,
      outcome: e.lastOutcomeLabel ?? "", contacted: yesNo(e.contacted), booked: yesNo(e.booked), attended: yesNo(e.attended), converted: yesNo(e.converted),
    })),
  );
}

function appointmentsSheet(wb: ExcelJS.Workbook, facts: ReportFacts) {
  const tz = facts.period.timezone;
  addSheet(
    wb,
    "Appointments",
    [
      { header: "Scheduled for", key: "at", width: 20 }, { header: "Patient", key: "patient", width: 24 }, { header: "Phone", key: "phone", width: 16 },
      { header: "Doctor", key: "doctor", width: 22 }, { header: "Branch", key: "branch", width: 18 }, { header: "Service", key: "service", width: 20 },
      { header: "Source", key: "source", width: 22 }, { header: "Status", key: "status", width: 14 }, { header: "Booked on", key: "booked", width: 14 },
      { header: "Reason (cancel / no-show / reschedule)", key: "reason", width: 34 },
    ],
    facts.appointments
      .filter((a) => a.scheduledInPeriod)
      .map((a) => ({
        at: dateTime(a.scheduledAt, tz), patient: a.patientName ?? UNKNOWN_PATIENT, phone: a.phone, doctor: a.doctorName ?? "", branch: a.branchName ?? "",
        service: a.service, source: a.sourceLabel ?? a.bucket, status: STATUS_LABEL[a.status] ?? a.status, booked: dayLabel(a.createdDay), reason: (a.reasonCode ?? "").replaceAll("_", " "),
      })),
  );
}

function followUpsSheet(wb: ExcelJS.Workbook, facts: ReportFacts) {
  const tz = facts.period.timezone;
  addSheet(
    wb,
    "Follow-ups",
    [
      { header: "Due", key: "due", width: 20 }, { header: "Type", key: "type", width: 22 }, { header: "Priority", key: "priority", width: 10 },
      { header: "Status", key: "status", width: 12 }, { header: "Overdue now", key: "overdue", width: 12 }, { header: "Patient", key: "patient", width: 24 },
      { header: "Phone", key: "phone", width: 16 }, { header: "Service", key: "service", width: 20 }, { header: "Assigned Team Member", key: "assignee", width: 24 },
      { header: "Completed", key: "completed", width: 20 }, { header: "Note", key: "notes", width: 40 },
    ],
    facts.followUps
      .filter((t) => t.dueInPeriod || t.completedInPeriod)
      .map((t) => ({
        due: dateTime(t.dueAt, tz), type: t.typeLabel ?? TASK_TYPE_LABEL[t.type] ?? t.type, priority: t.priority === "high" ? "High" : "Normal",
        status: STATUS_LABEL[t.status] ?? t.status, overdue: yesNo(t.overdue), patient: t.patientName ?? UNKNOWN_PATIENT, phone: t.phone, service: t.service ?? "",
        assignee: t.assignedTo ? (t.assigneeName ?? "Former staff") : "Unassigned", completed: dateTime(t.completedAt, tz), notes: t.notes ?? "",
      })),
  );
}

const NOT_RECORDED = "Date not recorded";

function proceduresSheet(wb: ExcelJS.Workbook, facts: ReportFacts, revenueTracking: boolean) {
  const tz = facts.period.timezone;
  // Scheduled for / Completed on / Payment date are three different facts; a missing one is said plainly, never filled in from another.
  addSheet(
    wb,
    "Procedures",
    [
      { header: "Procedure", key: "label", width: 30 }, { header: "Patient", key: "patient", width: 24 }, { header: "Phone", key: "phone", width: 16 },
      { header: "Service", key: "service", width: 20 }, { header: "Status", key: "status", width: 14 }, { header: "Scheduled for", key: "planned", width: 20 },
      { header: "Completed on", key: "completed", width: 20 }, ...(revenueTracking ? [{ header: "Payment date", key: "paid", width: 20 }] : []), { header: "Doctor", key: "doctor", width: 22 },
      { header: "Branch", key: "branch", width: 18 }, ...(revenueTracking ? [{ header: "Estimated value (₹)", key: "value", width: 18 }] : []),
      { header: "In this report", key: "counted", width: 40 },
    ],
    facts.procedures.map((p) => ({
      label: p.label, patient: p.patientName ?? UNKNOWN_PATIENT, phone: p.phone, service: p.service, status: p.status === "COMPLETED" ? "Completed" : "Scheduled",
      planned: p.plannedDate ? dateTime(p.plannedDate, tz) : NOT_RECORDED,
      completed: p.status !== "COMPLETED" ? "" : p.completedAt ? dateTime(p.completedAt, tz) : NOT_RECORDED,
      // A hospital with revenue tracking off gets no payment date and no rupee value in the file.
      ...(revenueTracking ? { paid: p.paymentAt ? dateTime(new Date(p.paymentAt), tz) : "", value: p.estimatedValue } : {}),
      doctor: p.doctorName ?? "Doctor not recorded", branch: p.branchName ?? "",
      // Reconciles every row with the screen's counts: which KPI (if any) this row is part of for the chosen period.
      counted: [p.plannedInPeriod && "Planned in period", p.completedInPeriod && "Completed in period"].filter(Boolean).join(" · ") || "Not counted — completion date not recorded",
    })),
  );
}

export interface ExportContext {
  hospital: string;
  generatedBy: string;
  filterLabels: [string, string][];
  /** False when the hospital has revenue tracking off. Absent = on. */
  revenueTracking?: boolean;
}

export async function buildReportWorkbook(db: Db, tenantId: string, kind: ReportExportKind, q: ReportQuery, ctx: ExportContext, now: Date = new Date()): Promise<{ buffer: Buffer; filename: string; rows: number }> {
  const facts = await loadReportFacts(db, tenantId, q, now);
  const wb = new ExcelJS.Workbook();
  wb.creator = "PulseOS";
  wb.created = now;
  if (kind === "summary") summarySheets(wb, facts);
  if (kind === "enquiries") enquiriesSheet(wb, facts);
  if (kind === "appointments") appointmentsSheet(wb, facts);
  if (kind === "follow-ups") followUpsSheet(wb, facts);
  if (kind === "procedures") proceduresSheet(wb, facts, ctx.revenueTracking !== false);
  filtersSheet(wb, facts.period, ctx.filterLabels, ctx.hospital, ctx.generatedBy, now);
  const rows = wb.worksheets.filter((w) => w.name !== "About").reduce((s, w) => s + Math.max(0, w.rowCount - 1), 0);
  const buffer = Buffer.from(await wb.xlsx.writeBuffer());
  const span = facts.period.from === facts.period.to ? facts.period.from : `${facts.period.from}_to_${facts.period.to}`;
  const slug = ctx.hospital.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 40) || "hospital";
  return { buffer, filename: `pulseos-${kind}-${slug}-${span}.xlsx`, rows };
}
