import ExcelJS from "exceljs";
import type { ReportExportKind, ReportPeriod, ReportQuery } from "@pulseos/types";
import type { Db } from "../../db/client.js";
import { buildOperationsReport, loadReportFacts, UNKNOWN_PATIENT, type ReportFacts } from "./operations-report.service.js";

// Real .xlsx workbooks (Office Open XML via exceljs) built from the SAME fact rows the on-screen report uses, so an
// export always matches what the user was looking at: same tenant, same period, same filters. Dates and times are
// written as text in the hospital's timezone ("02 Oct 2026, 11:00") so nobody's spreadsheet shifts them.

/** Hard ceiling per sheet — a period is at most 366 days, this only stops a pathological tenant from exhausting memory. */
export const EXPORT_ROW_LIMIT = 50_000;

export class ExportTooLargeError extends Error {}

type Col = { header: string; key: string; width: number };

const STATUS_LABEL: Record<string, string> = {
  requested: "Requested", scheduled: "Booked", confirmed: "Confirmed", checked_in: "Checked in", waiting: "Waiting", with_doctor: "With doctor",
  completed: "Completed", no_show: "No-show", cancelled: "Cancelled", pending: "Open", in_progress: "In progress",
};
const STAGE_LABEL: Record<string, string> = {
  enquiry: "Enquiry", contacted: "Contacted", booked: "Appointment booked", attended: "Visit attended", consulted: "Consultation completed",
  treatment_advised: "Procedure advised", scheduled: "Procedure scheduled", completed: "Procedure done", lost: "Lost",
};
const TASK_TYPE_LABEL: Record<string, string> = {
  CALLBACK: "Callback", FOLLOW_UP: "Follow-up", APPOINTMENT_CONFIRMATION: "Appointment confirmation", NO_SHOW_RECOVERY: "No-show recovery",
  TREATMENT_DECISION: "Treatment decision", POST_CARE: "Post-care", RECALL: "Recall", OTHER: "Other",
};
const RANGE_LABEL: Record<string, string> = { today: "Today", yesterday: "Yesterday", "7d": "Last 7 days", "30d": "Last 30 days", this_month: "This month", last_month: "Previous month", prev_month: "Previous month", "9d": "Last 9 days", "14d": "Last 14 days", "90d": "Last 90 days", custom: "Custom range" };

function dateTime(d: Date | null, timezone: string): string {
  if (!d) return "";
  return new Intl.DateTimeFormat("en-IN", { timeZone: timezone, day: "2-digit", month: "short", year: "numeric", hour: "2-digit", minute: "2-digit", hourCycle: "h23" }).format(d);
}

function dayLabel(ymd: string): string {
  return new Intl.DateTimeFormat("en-IN", { timeZone: "UTC", day: "2-digit", month: "short", year: "numeric" }).format(new Date(`${ymd}T00:00:00Z`));
}

const pct = (r: number | null) => (r === null ? "" : Math.round(r * 1000) / 10);
const yesNo = (b: boolean) => (b ? "Yes" : "No");

function addSheet(wb: ExcelJS.Workbook, name: string, cols: Col[], rows: object[]) {
  if (rows.length > EXPORT_ROW_LIMIT) throw new ExportTooLargeError(`${name}: ${rows.length} rows is more than ${EXPORT_ROW_LIMIT}; narrow the period or filters`);
  const ws = wb.addWorksheet(name, { views: [{ state: "frozen", ySplit: 1 }] });
  ws.columns = cols;
  ws.getRow(1).font = { bold: true };
  ws.getRow(1).fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FFE8F0FB" } };
  ws.addRows(rows);
  if (rows.length) ws.autoFilter = { from: { row: 1, column: 1 }, to: { row: 1, column: cols.length } };
  return ws;
}

function filtersSheet(wb: ExcelJS.Workbook, period: ReportPeriod, filterLabels: [string, string][], hospital: string, generatedBy: string, now: Date) {
  const ws = wb.addWorksheet("About");
  ws.columns = [{ header: "", key: "k", width: 26 }, { header: "", key: "v", width: 60 }];
  const rows: [string, string][] = [
    ["Hospital", hospital],
    ["Period", `${RANGE_LABEL[period.range] ?? period.range}: ${dayLabel(period.from)} – ${dayLabel(period.to)}`],
    ["Timezone", period.timezone],
    ...filterLabels,
    ["Generated", dateTime(now, period.timezone)],
    ["Generated by", generatedBy],
  ];
  ws.spliceRows(1, 1);
  for (const [k, v] of rows) ws.addRow({ k, v }).getCell(1).font = { bold: true };
}

